"""# Defining TCN
Defines the **PyTorch Temporal Convolutional Network (TCN) architecture**.
- `TemporalBlock` implements 1D dilated causal convolutions with residual connections, ReLU activations, and dropout to capture long-range sequence dependencies without data leakage.
- `TCN class` stacks these blocks across increasing dilation rates and passes the final time step through a linear output layer for single-step target forecasting.
"""

class TemporalBlock(nn.Module):
    def __init__(self, in_channels, out_channels, kernel_size, dilation, dropout=0.2):
        super().__init__()
        padding = (kernel_size - 1) * dilation
        self.conv1 = nn.Conv1d(in_channels, out_channels, kernel_size,
                               padding=padding, dilation=dilation)
        self.relu1 = nn.ReLU()
        self.dropout1 = nn.Dropout(dropout)
        self.conv2 = nn.Conv1d(out_channels, out_channels, kernel_size,
                               padding=padding, dilation=dilation)
        self.relu2 = nn.ReLU()
        self.dropout2 = nn.Dropout(dropout)
        self.downsample = nn.Conv1d(in_channels, out_channels, 1) if in_channels != out_channels else None
        self.init_weights()

    def init_weights(self):
        for m in self.modules():
            if isinstance(m, nn.Conv1d):
                nn.init.kaiming_normal_(m.weight, mode='fan_in', nonlinearity='relu')
                if m.bias is not None:
                    nn.init.constant_(m.bias, 0)

    def forward(self, x):
        out = self.conv1(x)
        out = self.relu1(out)
        out = self.dropout1(out)
        out = self.conv2(out)
        out = self.relu2(out)
        out = self.dropout2(out)
        res = x if self.downsample is None else self.downsample(x)
        _, _, length = res.shape
        out = out[:, :, :length]
        return self.relu2(out + res)


class TCN(nn.Module):
    def __init__(self, input_dim, output_dim=1, num_channels=64, kernel_size=3, dilations=None, dropout=0.2):
        super().__init__()
        if dilations is None:
            dilations = [1, 2, 4, 8, 16]
        self.blocks = nn.ModuleList()
        in_ch = input_dim
        for d in dilations:
            self.blocks.append(TemporalBlock(in_ch, num_channels, kernel_size, d, dropout))
            in_ch = num_channels
        self.fc = nn.Linear(num_channels, output_dim)

    def forward(self, x):
        x = x.permute(0, 2, 1)
        for block in self.blocks:
            x = block(x)
        x = x[:, :, -1]
        return self.fc(x).squeeze(-1)

