"""# TCN preprocessing
- Implements feature-level preprocessing for the TCN model
- Takes raw multi-feature rows and applies sequence-ready scaling: log-transform and Z-score standardization on prices, pre-fitted PowerTransformations on volume and rolling volatility metrics, and standard scaling on returns
- Returns a vectorized float32 array aligned with the TCN input dimensions
"""

def preprocess_for_tcn(raw_row, preprocessors):
    price, vol, ret, vol7, vol30, anomaly = raw_row
    price_log = np.log(price)
    price_scaled = (price_log - preprocessors['price_mean']) / preprocessors['price_std']
    vol_scaled   = preprocessors['pt_vol'].transform([[vol]])[0,0]
    vol7_scaled  = preprocessors['pt_vol7'].transform([[vol7]])[0,0]
    vol30_scaled = preprocessors['pt_vol30'].transform([[vol30]])[0,0]
    ret_scaled = preprocessors['scaler_return'].transform([[ret]])[0,0]
    return np.array([price_scaled, vol_scaled, ret_scaled, vol7_scaled, vol30_scaled, anomaly], dtype=np.float32)

"""# Helper Functions

## Predict dataset
- Constructs 30-day rolling sequence windows (seq_len = 30) and aligns targets for time-series forecasting
- Generates predictions for XGBoost using the latest raw feature vector and for TCN using preprocessed sequence tensors
- Combines model predictions via a weighted linear ensemble ($39\%$ TCN weight and $61\%$ XGBoost weight).
"""

SEQ_LEN = 30
TCN_WEIGHT = 0.39

def predict_dataset(X_raw, y_raw, seq_len=SEQ_LEN, tcn_weight=TCN_WEIGHT):
    """Creates windows and generates predictions for XGBoost, TCN, and Ensemble."""
    # 1. Build sequence windows
    X_windows, y_aligned = [], []
    for i in range(len(X_raw) - seq_len):
        X_windows.append(X_raw[i:i + seq_len])
        y_aligned.append(y_raw[i + seq_len])

    X_windows = np.array(X_windows)
    y_aligned = np.array(y_aligned)

    # 2. Get predictions
    xgb_preds, tcn_preds = [], []
    for window in X_windows:
        # XGBoost prediction
        latest_raw = window[-1].reshape(1, -1)
        xgb_preds.append(xgb_model.predict(latest_raw)[0])

        # TCN prediction
        scaled_window = np.array([preprocess_for_tcn(row, preprocessors) for row in window])
        tcn_input = torch.tensor(scaled_window, dtype=torch.float32).unsqueeze(0).to(device)
        with torch.no_grad():
            tcn_preds.append(tcn_model(tcn_input).item())

    xgb_preds = np.array(xgb_preds)
    tcn_preds = np.array(tcn_preds)
    ensemble_preds = tcn_weight * tcn_preds + (1 - tcn_weight) * xgb_preds

    return y_aligned, xgb_preds, tcn_preds, ensemble_preds

"""## Evaluation Function
- A function for defining the evaluation metrics used for evaluating the model performance
- Include `MAE`, `RMSE`, `Directional Accuracy` and `R²`
"""

def evaluate_and_print(y_true, xgb_preds, tcn_preds, ensemble_preds, title="PERFORMANCE"):
    """Calculates metrics and formats output."""
    def compute_metrics(y_true, y_pred):
        mae = mean_absolute_error(y_true, y_pred)
        rmse = np.sqrt(mean_squared_error(y_true, y_pred))
        da = np.mean((y_true > 0) == (y_pred > 0)) * 100
        r2 = r2_score(y_true, y_pred)
        return mae, rmse, da, r2  # <-- Add r2 here

    xgb_mae, xgb_rmse, xgb_da, xgb_r2 = compute_metrics(y_true, xgb_preds)
    tcn_mae, tcn_rmse, tcn_da, tcn_r2 = compute_metrics(y_true, tcn_preds)
    ens_mae, ens_rmse, ens_da, ens_r2 = compute_metrics(y_true, ensemble_preds)

    print("\n" + "=" * 70)
    print(f"FINAL {title.upper()}")
    print("=" * 60)
    print(f"XGBoost   : MAE = {xgb_mae:.4f}, RMSE = {xgb_rmse:.4f}, DA = {xgb_da:.4f}%, R2 = {xgb_r2:.4f}")
    print(f"TCN       : MAE = {tcn_mae:.4f}, RMSE = {tcn_rmse:.4f}, DA = {tcn_da:.4f}%, R2 = {tcn_r2:.4f}")
    print(f"Ensemble  : MAE = {ens_mae:.4f}, RMSE = {ens_rmse:.4f}, DA = {ens_da:.4f}%, R2 = {ens_r2:.4f}")
    print("=" * 70)

