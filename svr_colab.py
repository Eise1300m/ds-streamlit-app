"""## Load Datafile
Load the pre-split, pre-scaled train/test CSVs. SVR is a distance/kernel-based model, so it needs the scaled feature set (Toolbox B), not the raw/unscaled one.
"""

X_train = pd.read_csv("X_train_trans_scaled.csv")
X_test  = pd.read_csv("X_test_trans_scaled.csv")
y_train = pd.read_csv("y_train.csv").squeeze()
y_test  = pd.read_csv("y_test.csv").squeeze()

print("X_train:", X_train.shape, "| X_test:", X_test.shape)

"""## Evaluation Function
Reusable function that reports MAE (4 dp), RMSE (4 dp), R² (4 dp), and Directional Accuracy (2 dp), so every model in the team's notebooks reports metrics in the same format.
"""

def evaluate(y_true, y_pred, label="Model"):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)
    da = (np.sign(y_pred) == np.sign(y_true)).mean() * 100

    print(f"=== {label} — Test Set Performance ===")
    print(f"MAE  : {mae:.4f}")
    print(f"RMSE : {rmse:.4f}")
    print(f"R2   : {r2:.4f}")
    print(f"DA   : {da:.2f}%")

    return {"MAE": mae, "RMSE": rmse, "R2": r2, "DA": da}

"""## Main Modelling
Hyperparameter search with `RandomizedSearchCV` over `TimeSeriesSplit` folds (not standard k-fold, which would let future folds leak into training on chronological data), then fit the best estimator on the full training set and evaluate it on the held-out test set.
"""

param_grid = [
    {'kernel': ['rbf'], 'C': [0.01, 0.1, 1, 10, 50, 100],
     'epsilon': [0.05, 0.1, 0.3, 0.5, 0.8], 'gamma': ['scale', 'auto', 0.01, 0.1]},
    {'kernel': ['linear'], 'C': [0.01, 0.1, 1, 10, 50, 100],
     'epsilon': [0.05, 0.1, 0.3, 0.5, 0.8]}
]

svr_search = RandomizedSearchCV(
    SVR(), param_grid, n_iter=30, cv=TimeSeriesSplit(n_splits=5),
    scoring='neg_mean_absolute_error', n_jobs=-1, random_state=42
)
svr_search.fit(X_train, y_train)

svr_final = svr_search.best_estimator_
print("Best params:", svr_search.best_params_)

y_pred_eval = svr_final.predict(X_test)
metrics = evaluate(y_test, y_pred_eval, label="Final SVR")

"""Observations & Insights: An optimal C of 0.01 and epsilon of 0.8 indicates a strong regularization penalty within the RBF kernel.
- In financial time-series forecasting, features often exhibit multi-collinearity and noise.
- A low C value prevents overfitting on historical market noise by prioritizing a wider margin and minimizing the influence of individual data points.
> Error Metrics (MAE: 0.6389, RMSE: 0.9163): The relatively low error rates confirm robust generalization on the test set, proving the chosen parameters successfully managed the noise-to-signal ratio.
> R2 Score (-0.0148): Near-zero R2 reflects the random-walk nature of daily financial returns, showing that even non-linear kernels struggle to capture exact point-by-point return variance.
. Directional Accuracy (60.56%): Heavily outperforms a 50% random coin toss, proving that the RBF kernel's feature inputs successfully capture predictive market timing signals.
"""

