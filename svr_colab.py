def on_predict_click(b):
    with output_display:
        clear_output()
        print("Processing input data using preprocessors.pkl...")

        p_lag = price_input.value
        v_lag = vol_input.value
        r_lag = ret_input.value
        v7 = vol7_input.value
        v30 = vol30_input.value
        is_anom = anomaly_input.value

        try:
            # A. Toolbox B Transformations using preprocessors.pkl keys
            price_log = np.log(p_lag)
            price_scaled = (price_log - preprocessors['price_mean']) / preprocessors['price_std']
            vol_scaled   = preprocessors['pt_vol'].transform([[v_lag]])[0,0]
            ret_scaled   = preprocessors['scaler_return'].transform([[r_lag]])[0,0]
            vol7_scaled  = preprocessors['pt_vol7'].transform([[v7]])[0,0]
            vol30_scaled = preprocessors['pt_vol30'].transform([[v30]])[0,0]

            # Construct the final scaled array in the correct Toolbox B order
            scaled_array = np.array([[price_scaled, vol_scaled, ret_scaled, vol7_scaled, vol30_scaled, is_anom]])

            # B. SVR Prediction
            pred_return = svr_model.predict(scaled_array)[0]

            # C. Price Reconstruction
            pred_price = p_lag * (1 + (pred_return / 100))

            print("-" * 40)
            print("✅ SVR PREDICTION SUCCESSFUL")
            print(f"-> Predicted Daily Return : {pred_return:+.4f}%")
            print(f"-> Reconstructed Price    : ₹{pred_price:,.2f}")
            print("-" * 40)

        except Exception as e:
            print(f"❌ Error during prediction: {e}")

